"""### 6. Metin Temizleme (Preprocessing)
Duygu analizi modelinin daha doğru çalışabilmesi için metin üzerinde çeşitli
temizleme işlemleri uygulanmıştır. Bu adımda:

- Tüm metin küçük harfe dönüştürülmüş,
- Noktalama işaretleri ve özel karakterler kaldırılmış,
- `stopwords` olarak bilinen anlamsız bağlaç ve sık kullanılan kelimeler çıkarılmış,
- Kelimeler köklerine indirgenmiş (lemmatization).

Bu işlemler metnin daha sade hale gelmesini sağlayarak modelin performansını
arttırmayı amaçlamaktadır.

"""

#nlp temizliği(lowercase/stopwords/lemma)
 # LOWERCASE: Tüm metni küçük harfe çevirerek tutarlılık sağlar.
 #REMOVE PUNCTUATION & SPECIAL CHARACTERS:Harf ve boşluk dışındaki karakterleri temizler (noktalama, rakam, semboller).
 # TOKENIZATION: Metni kelimelere böler.
 # STOPWORDS REMOVAL:"the, is, and, of" gibi anlam taşımayan kelimeleri çıkarır.
 # LEMMATIZATION:Kelimeleri kök hâline indirger (cars → car, repairing → repair).

from nltk.corpus import stopwords
from nltk.tokenize import word_tokenize
from nltk.stem import WordNetLemmatizer
import re

stop_words = set(stopwords.words("english"))
lemma = WordNetLemmatizer()

def clean_text(t):
    t = t.lower()
    t = re.sub(r"[^a-zA-Z\s]", "", t)
    tokens = word_tokenize(t)
    tokens = [w for w in tokens if w not in stop_words]
    tokens = [lemma.lemmatize(w) for w in tokens]
    return " ".join(tokens)

df_sentiment["clean"] = df_sentiment["sentence"].apply(clean_text)
df_sentiment[["sentence", "clean", "label"]]

#CONFUSION MATRIX (Isı Haritası)
