from sklearn.linear_model import LogisticRegression

# Re-define X, y, X_tfidf, X_train, X_test, y_train, y_test, model, y_pred for standalone execution
X = df_sentiment["clean"]
y = df_sentiment["label"]

tfidf = TfidfVectorizer(max_features=2000)
X_tfidf = tfidf.fit_transform(X)

X_train, X_test, y_train, y_test = train_test_split(
    X_tfidf, y, test_size=0.3, random_state=42
)

model = LogisticRegression(max_iter=200)
model.fit(X_train, y_train)

y_pred = model.predict(X_test)

cm = confusion_matrix(y_test, y_pred)
labels = sorted(y.unique())

plt.figure(figsize=(6,4))
sns.heatmap(cm, annot=True, fmt='d', cmap="Blues",
            xticklabels=labels, yticklabels=labels)
plt.xlabel("Tahmin Edilen")
plt.ylabel("Gerçek")
plt.title("Confusion Matrix")
plt.show()

#TF-IDF EN ÖNEMLİ KELİMELER (Feature Importance)
