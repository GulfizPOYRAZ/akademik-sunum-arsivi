"""### 4. VADER ile Duygu Skorlarının Hesaplanması
Bu aşamada her bir cümle için VADER duygu analiz modeli kullanılarak
compound duygu skorları hesaplanmıştır. VADER modeli, metinlerdeki
olumlu, olumsuz ve nötr ifadeleri analiz ederek -1 ile +1 arasında
bir skor üretir. Bu skor:
- +0.02 üzeri → Pozitif
- -0.05 altı → Negatif
- Aradaki değerler → Nötr
olarak sınıflandırılmıştır.

"""

#vader duygu analizi
from nltk.sentiment import SentimentIntensityAnalyzer
import pandas as pd

sia = SentimentIntensityAnalyzer()

results = []
for s in sentences:
    score = sia.polarity_scores(s)
    results.append({
        "sentence": s,
        "compound": score["compound"]
    })

df_sentiment = pd.DataFrame(results)
df_sentiment

#etiketleme(pozitif/negatif/nötr)
def label_sentiment(c):
    if c >= 0.02:          # eşik düşürüldü → daha fazla Positive çıkacak
        return "Positive"
    elif c <= -0.05:
        return "Negative"
    else:
        return "Neutral"

df_sentiment["label"] = df_sentiment["compound"].apply(label_sentiment)

